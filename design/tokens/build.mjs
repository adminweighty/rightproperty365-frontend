// Generates tokens.css from tokens.json and checks WCAG contrast for the
// colour pairs the UI relies on. Run with `npm run tokens`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(dir, "tokens.json"), "utf8"));
const { theme, ...base } = tokens;

const flatten = (node, path = []) =>
  Object.entries(node).flatMap(([key, value]) => {
    if (key.startsWith("$")) return [];
    return typeof value === "object"
      ? flatten(value, [...path, key])
      : [[[...path, key], value]];
  });

const varName = (path) => `--rp-${path.join("-")}`;
const toCss = (value) =>
  String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(${varName(ref.split("."))})`);
const block = (entries) =>
  entries.map(([path, value]) => `  ${varName(path)}: ${toCss(value)};`).join("\n");

const baseVars = block(flatten(base));
const light = block(flatten(theme.light));
const dark = block(flatten(theme.dark));

const css = `/* GENERATED by design/tokens/build.mjs from tokens.json. Do not edit by hand. */

:root {
${baseVars}

${light}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${dark}
  color-scheme: dark;
}
`;

writeFileSync(join(dir, "tokens.css"), css);

// ---- Contrast check -------------------------------------------------------
const resolve = (value) => {
  const match = /^\{([^}]+)\}$/.exec(value);
  if (!match) return value;
  return resolve(match[1].split(".").reduce((node, key) => node[key], base));
};
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// [foreground, background, minimum ratio]
const pairs = [
  ["text.ink", "bg.page", 4.5],
  ["text.muted", "bg.page", 4.5],
  ["text.subtle", "bg.page", 4.5],
  ["text.muted", "bg.sunken", 4.5],
  ["text.subtle", "bg.surface", 4.5],
  ["text.inverse", "bg.inverse", 4.5],
  ["brand.on", "brand.base", 4.5],
  ["brand.on", "brand.deep", 4.5],
  ["brand.accent", "brand.base", 4.5],
  ["brand.deep", "brand.accent", 4.5],
  ["brand.logo", "bg.page", 4.5],
  ["brand.logo", "bg.sunken", 4.5],
  ["primary.on", "primary.base", 4.5],
  ["primary.on", "primary.hover", 4.5],
  ["primary.ink", "primary.soft", 4.5],
  ["primary.ink", "bg.page", 4.5],
  ["accent.ink", "accent.soft", 4.5],
  ["success.base", "success.soft", 4.5],
  ["warning.base", "warning.soft", 4.5],
  ["danger.base", "danger.soft", 4.5],
  ["danger.base", "bg.surface", 4.5],
  ["info.base", "info.soft", 4.5],
  ["border.control", "bg.surface", 3],
  ["border.control", "bg.page", 3],
  ["focus", "bg.page", 3],
  ["focus", "bg.surface", 3],
];

let failures = 0;
for (const mode of ["light", "dark"]) {
  const get = (key) =>
    resolve(key.split(".").reduce((node, part) => node[part], theme[mode].color));
  for (const [fg, bg, min] of pairs) {
    const value = ratio(get(fg), get(bg));
    const ok = value >= min;
    if (!ok) failures += 1;
    console.log(
      `${ok ? "ok  " : "FAIL"} ${mode.padEnd(5)} ${fg.padEnd(15)} on ${bg.padEnd(13)} ${value.toFixed(2)}:1 (min ${min})`,
    );
  }
}

console.log(`\nWrote tokens.css. ${failures ? `${failures} contrast failure(s).` : "All contrast checks pass."}`);
process.exit(failures ? 1 : 0);
